namespace App\Tests;

use IQ2i\HerseBundle\Event\TwoFactorFailedEvent;
use IQ2i\HerseBundle\Event\TwoFactorSucceededEvent;
use IQ2i\HerseBundle\TrustedDevice\TrustLevel;
use PHPUnit\Framework\Attributes\PreserveGlobalState;
use PHPUnit\Framework\Attributes\RunTestsInSeparateProcesses;
use Scheb\TwoFactorBundle\Model\Email\TwoFactorInterface;
use Symfony\Component\EventDispatcher\EventDispatcherInterface;
use Symfony\Component\HttpFoundation\Response;

/**
 * The administration of Moka asks for a code sent by email, and a device trusted by the administrator skips it afterwards.
 *
 * In its own processes: the user class generated by Moka differs from the one of the other tests, under the same name.
 */
#[RunTestsInSeparateProcesses]
#[PreserveGlobalState(false)]
final class TwoFactorTest extends MokaKernelTestCase
{
    /** @var list<TwoFactorSucceededEvent|TwoFactorFailedEvent> */
    private array $twoFactorEvents = [];

    protected static function environment(): string
    {
        return 'test_two_factor';
    }

    protected function setUp(): void
    {
        parent::setUp();

        $this->twoFactorEvents = [];
        $dispatcher = $this->service(EventDispatcherInterface::class, 'event_dispatcher');
        $dispatcher->addListener(TwoFactorSucceededEvent::class, function (TwoFactorSucceededEvent $event): void {
            $this->twoFactorEvents[] = $event;
        });
        $dispatcher->addListener(TwoFactorFailedEvent::class, function (TwoFactorFailedEvent $event): void {
            $this->twoFactorEvents[] = $event;
        });
    }

    public function testTheCodeIsSentByTheMailerOfTheBundleAndCompletesTheLogin(): void
    {
        $this->createAdmin();

        $this->login();
        $this->assertSecondFactorAsked();

        self::assertSame(['Your sign-in code'], $this->mailSubjects(), 'The code only: the device is registered, and the user warned, once the login is complete.');
        self::assertSame('admin@example.com', $this->mails()[0]->getTo()[0]->getAddress());
        self::assertSame([], $this->devices());

        $form = $this->send('GET', '/admin/2fa');
        self::assertSame(200, $form->getStatusCode());
        self::assertStringContainsString('name="_auth_code"', (string) $form->getContent());
        self::assertStringContainsString('name="_trusted"', (string) $form->getContent());

        $this->submitCode($this->emailedCode());

        $this->assertLoggedIn();
        self::assertCount(1, $this->twoFactorEvents);
        self::assertInstanceOf(TwoFactorSucceededEvent::class, $this->twoFactorEvents[0]);
        self::assertSame('admin', $this->twoFactorEvents[0]->reference?->type);
        self::assertSame('moka', $this->twoFactorEvents[0]->firewall);

        $devices = $this->devices();
        self::assertCount(1, $devices);
        self::assertSame(TrustLevel::Known, $devices[0]->getTrustLevel());
        self::assertCount(2, $this->mails(), 'The code, then the new device warning.');
    }

    public function testAWrongCodeIsRefused(): void
    {
        $this->createAdmin();
        $this->login();

        $this->submitCode('000000');

        $this->assertSecondFactorAsked();
        self::assertCount(1, $this->twoFactorEvents);
        self::assertInstanceOf(TwoFactorFailedEvent::class, $this->twoFactorEvents[0]);
        self::assertSame([], $this->devices());
    }

    public function testAVerifiedDeviceSkipsTheSecondFactor(): void
    {
        $this->createAdmin();
        $this->login();
        $this->submitCode($this->emailedCode(), trustDevice: true);

        self::assertSame(TrustLevel::Verified, $this->devices()[0]->getTrustLevel());
        $codes = \count($this->mails());

        // The browser comes back: the device cookie stays, the session is gone.
        unset($this->cookies['MOCKSESSID']);
        $this->login();

        $this->assertLoggedIn();
        self::assertCount($codes, $this->mails(), 'No second code is sent.');
    }

    public function testADeviceThatWasNotTrustedIsAskedForTheSecondFactorAgain(): void
    {
        $this->createAdmin();
        $this->login();
        $this->submitCode($this->emailedCode());

        unset($this->cookies['MOCKSESSID']);
        $this->login();

        $this->assertSecondFactorAsked();
    }

    public function testAnAdministratorWithoutTheSecondFactorIsNotAsked(): void
    {
        $this->createAdmin(secondFactor: false);

        $this->login();

        $this->assertLoggedIn();
        self::assertNotContains('Your sign-in code', $this->mailSubjects());
    }

    public function testTheUserClassGeneratedByMokaCarriesTheSecondFactor(): void
    {
        $admin = $this->reload($this->createAdmin());

        self::assertInstanceOf(TwoFactorInterface::class, $admin);
        self::assertTrue($admin->isEmailAuthEnabled());
        self::assertSame('admin@example.com', $admin->getEmailAuthRecipient());
    }

    public function testTheSecondFactorIsSwitchedOnFromTheUserScreenOfMoka(): void
    {
        $admin = $this->createAdmin(secondFactor: false);
        $user = $this->createAdmin('redactor@example.com', secondFactor: false);
        $this->login();

        $screen = $this->send('GET', '/admin/user/'.$user->getId());
        self::assertSame(200, $screen->getStatusCode());
        self::assertStringContainsString('name="user[emailAuthEnabled]"', (string) $screen->getContent());

        $response = $this->send('POST', '/admin/user/'.$user->getId(), ['_method' => 'PUT', 'user' => [
            'firstName' => 'Redactor',
            'lastName' => 'Moka',
            'email' => 'redactor@example.com',
            'isActive' => '1',
            'locale' => 'en_GB',
            'role' => 'ROLE_REDACTOR',
            'emailAuthEnabled' => '1',
            '_token' => $this->hiddenField($screen, 'user[_token]'),
        ]]);

        self::assertSame(302, $response->getStatusCode());
        $reloaded = $this->reload($user);
        self::assertInstanceOf(TwoFactorInterface::class, $reloaded);
        self::assertTrue($reloaded->isEmailAuthEnabled());
        self::assertSame($admin->getId(), $this->reload($admin)->getId());
    }

    private function submitCode(string $code, bool $trustDevice = false): Response
    {
        return $this->send('POST', '/admin/2fa_check', ['_auth_code' => $code] + ($trustDevice ? ['_trusted' => '1'] : []));
    }

    private function emailedCode(): string
    {
        foreach (array_reverse($this->mails()) as $mail) {
            if (1 === preg_match('/sign-in code is: (\d+)/', (string) $mail->getHtmlBody(), $matches)) {
                return $matches[1];
            }
        }

        self::fail('An email with the code was expected.');
    }

    private function assertSecondFactorAsked(): void
    {
        $this->assertRedirectedTo('/admin/2fa', $this->send('GET', '/admin/'));
    }

    private function assertLoggedIn(): void
    {
        self::assertSame(200, $this->send('GET', '/admin/')->getStatusCode());
    }
}
